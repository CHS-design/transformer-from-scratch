# ============ 模型结构 ============

# 模型内部所有向量/隐藏状态的统一宽度，即词嵌入维度。
# 任何词进入模型后都表示为 D_MODEL 维向量；注意力的投影矩阵是
# D_MODEL x D_MODEL 的方阵，FFN 的输入输出也是 D_MODEL 维。
# 注意：必须能被 N_HEADS 整除，多头才能均分维度。
D_MODEL = 512

# 多头注意力的头数（"视角"数）。每个头分到 D_MODEL // N_HEADS = 64 维，
# 各头独立计算"该关注谁"后再拼接。头多则视角广而浅，头少则窄而深；
# 由于每头只算 64 维，多头并行几乎不增加总计算量。
# 硬约束：D_MODEL % N_HEADS 必须等于 0。
N_HEADS = 8

# Encoder 和 Decoder 各自堆叠的层数（各 6 层，全模型合计 12 层）。
# 层数 = 加工深度：底层学局部特征，越往上表示越抽象。
# 敢堆这么深，靠的是残差连接 + LayerNorm 这对保命组合。
N_LAYERS = 6

# FFN（前馈网络）中间层宽度：D_MODEL -> D_FF -> D_MODEL，
# 先膨胀 4 倍做非线性加工，再压回原宽度。
# FFN 约占全模型 2/3 的参数量，被认为是模型"存知识"的地方。
D_FF = 2048

# ============ 训练策略 ============

# Dropout 比例：训练时每步随机将 10% 的激活值置零，防止过拟合；
# 推理时自动关闭（model.eval() 下不生效）。
DROPOUT = 0.1

# ============ 序列限制 ============

# 位置编码支持的最大句长（token 数上限），超出需截断。
# Multi30k 语料均为短句，150 留有余量。
MAX_LEN = 150

# ============ 训练策略 ============
BATCH_SIZE = 64        # 一批几句：GPU 装箱容量（4GB 显存如果溢出就降到 32）
EPOCHS = 20            # 全部训练数据过几遍
LEARNING_RATE = 5e-4   # 每次参数更新的步子大小：太大 loss 飞天，太小龟速

# ============ 早停 ============
PATIENCE = 5           # 连续 N 轮验证 loss 无改善就早停


